"""Project the STL onto X-Z, X-Y, Y-Z planes and emit a 3-up SVG silhouette.
No deps beyond stdlib — purely for sanity-check visualization."""
import struct
import sys
import os

def load_stl(path):
    with open(path, 'rb') as f:
        f.read(80)
        (n,) = struct.unpack('<I', f.read(4))
        tris = []
        for _ in range(n):
            data = struct.unpack('<12fH', f.read(50))
            v = [(data[3 + 3*i], data[4 + 3*i], data[5 + 3*i]) for i in range(3)]
            tris.append(v)
        return tris

def project(tris, ax, ay):
    """Return list of (x,y) triangles for projection onto axes (ax, ay)."""
    out = []
    for v in tris:
        out.append([(p[ax], p[ay]) for p in v])
    return out

def bounds_2d(tris2d):
    xs = [p[0] for t in tris2d for p in t]
    ys = [p[1] for t in tris2d for p in t]
    return min(xs), min(ys), max(xs), max(ys)

def svg_view(tris2d, title, w=400, h=400, pad=20):
    minx, miny, maxx, maxy = bounds_2d(tris2d)
    rng_x = maxx - minx
    rng_y = maxy - miny
    scale = min((w - 2*pad) / rng_x, (h - 2*pad) / rng_y)
    cx = w / 2 - (minx + maxx) / 2 * scale
    cy = h / 2 + (miny + maxy) / 2 * scale

    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" style="background:#0a0a0a;border:1px solid #333">']
    parts.append(f'<text x="10" y="20" fill="#aaa" font-family="monospace" font-size="12">{title}</text>')
    parts.append(f'<text x="10" y="{h-10}" fill="#666" font-family="monospace" font-size="10">range: {rng_x:.1f} × {rng_y:.1f} mm</text>')
    for t in tris2d:
        pts = ' '.join(f'{p[0]*scale+cx:.1f},{-p[1]*scale+cy:.1f}' for p in t)
        parts.append(f'<polygon points="{pts}" fill="rgba(120,180,255,0.04)" stroke="rgba(120,180,255,0.5)" stroke-width="0.4"/>')
    parts.append('</svg>')
    return '\n'.join(parts)

def main(stl_path, out_path):
    tris = load_stl(stl_path)
    print(f'Loaded {len(tris)} triangles from {stl_path}')

    front = svg_view(project(tris, 0, 2), 'Front (X-Z, looking -Y)')
    side  = svg_view(project(tris, 1, 2), 'Side (Y-Z, looking +X)')
    top   = svg_view(project(tris, 0, 1), 'Top (X-Y, looking -Z)')

    html = f"""<!doctype html>
<html><head><title>printedpipes P-trap v0</title>
<style>body {{ background:#000;color:#ccc;font-family:monospace;margin:20px }}
.row {{ display:flex; gap:20px; flex-wrap:wrap }}
.cell {{ flex:1; min-width:400px }}</style></head>
<body>
<h2>P-trap v0 — orthographic projections</h2>
<p>1½&quot; PVC DWV, integrated U-bend + 90° + 150mm trap arm. Generated by Manifold-3D.</p>
<div class="row">
  <div class="cell">{front}</div>
  <div class="cell">{side}</div>
  <div class="cell">{top}</div>
</div>
</body></html>
"""
    with open(out_path, 'w') as f:
        f.write(html)
    print(f'Wrote {out_path}')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
